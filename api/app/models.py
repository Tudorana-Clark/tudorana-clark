"""Domain models and API contracts. Validation happens here, at the boundary."""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Annotated

from pydantic import BaseModel, ConfigDict, EmailStr, Field, HttpUrl, StringConstraints, field_validator

ShortText = Annotated[str, StringConstraints(strip_whitespace=True, max_length=300)]
Slug = Annotated[str, StringConstraints(pattern=r"^[a-z0-9]+(?:-[a-z0-9]+)*$", max_length=120)]


def utcnow() -> datetime:
    return datetime.now(UTC)


class Kind(StrEnum):
    article = "article"
    research = "research"
    note = "note"
    talk = "talk"
    video = "video"


class Status(StrEnum):
    draft = "draft"
    published = "published"


class Image(BaseModel):
    url: HttpUrl
    alt: ShortText = ""
    width: int | None = None
    height: int | None = None


class FaqItem(BaseModel):
    question: ShortText
    answer: Annotated[str, StringConstraints(strip_whitespace=True, max_length=1200)]


class Stat(BaseModel):
    value: Annotated[str, StringConstraints(strip_whitespace=True, max_length=40)]
    label: ShortText


class SeoPack(BaseModel):
    """Everything search engines and answer engines read. Generated by AI, editable by hand."""

    meta_title: Annotated[str, StringConstraints(strip_whitespace=True, max_length=70)] = ""
    meta_description: Annotated[str, StringConstraints(strip_whitespace=True, max_length=170)] = ""
    keywords: list[ShortText] = Field(default_factory=list, max_length=15)
    tldr: Annotated[str, StringConstraints(strip_whitespace=True, max_length=600)] = ""
    key_takeaways: list[ShortText] = Field(default_factory=list, max_length=7)
    faq: list[FaqItem] = Field(default_factory=list, max_length=8)
    entities: list[ShortText] = Field(default_factory=list, max_length=15)


class SocialCopy(BaseModel):
    linkedin: Annotated[str, StringConstraints(max_length=3000)] = ""
    x: Annotated[str, StringConstraints(max_length=280)] = ""
    facebook: Annotated[str, StringConstraints(max_length=2000)] = ""
    threads: Annotated[str, StringConstraints(max_length=500)] = ""
    bluesky: Annotated[str, StringConstraints(max_length=300)] = ""


class EventInfo(BaseModel):
    name: ShortText
    date: datetime
    location: ShortText = ""
    url: HttpUrl | None = None


class VideoInfo(BaseModel):
    embed_url: HttpUrl
    duration_iso: Annotated[str, StringConstraints(pattern=r"^P(T(\d+H)?(\d+M)?(\d+S)?)$")] | None = None
    thumbnail: Image | None = None


class ResearchInfo(BaseModel):
    pdf_url: HttpUrl | None = None
    carousel_url: HttpUrl | None = None
    institution: ShortText = ""
    citation: Annotated[str, StringConstraints(max_length=1000)] = ""
    stats: list[Stat] = Field(default_factory=list, max_length=8)


class CoverInfo(BaseModel):
    """Provenance of an AI-generated feature image, so covers can be audited and re-rendered when the style kit changes."""

    style_version: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=40)]
    model: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=120)]
    concept: ShortText
    generated_at: datetime


class ContentIn(BaseModel):
    """What the studio sends when creating or updating a piece of content."""

    model_config = ConfigDict(extra="forbid")

    kind: Kind
    title: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
    slug: Slug | None = None
    subtitle: ShortText = ""
    excerpt: Annotated[str, StringConstraints(strip_whitespace=True, max_length=400)] = ""
    body: Annotated[str, StringConstraints(max_length=200_000)] = ""
    category: ShortText = ""
    tags: list[ShortText] = Field(default_factory=list, max_length=12)
    feature_image: Image | None = None
    # Set only while feature_image is an AI cover; cleared when a real photo is uploaded.
    cover: CoverInfo | None = None
    featured: bool = False
    seo: SeoPack = Field(default_factory=SeoPack)
    social: SocialCopy = Field(default_factory=SocialCopy)
    event: EventInfo | None = None
    video: VideoInfo | None = None
    research: ResearchInfo | None = None
    # Optional backdate (e.g. posts migrated from Ghost). Defaults to the first publish time.
    published_at: datetime | None = None

    @field_validator("tags")
    @classmethod
    def dedupe_tags(cls, v: list[str]) -> list[str]:
        seen: dict[str, str] = {}
        for t in v:
            if t and t.lower() not in seen:
                seen[t.lower()] = t
        return list(seen.values())


class Content(ContentIn):
    model_config = ConfigDict(extra="ignore")

    id: str
    slug: Slug
    status: Status = Status.draft
    created_at: datetime = Field(default_factory=utcnow)
    updated_at: datetime = Field(default_factory=utcnow)
    reading_minutes: int = 1
    word_count: int = 0


class ContentSummary(BaseModel):
    """Lightweight projection used by listing pages."""

    id: str
    kind: Kind
    slug: str
    title: str
    excerpt: str
    category: str
    tags: list[str]
    feature_image: Image | None
    featured: bool
    status: Status
    published_at: datetime | None
    updated_at: datetime
    reading_minutes: int
    event: EventInfo | None = None
    video: VideoInfo | None = None


class ContentList(BaseModel):
    items: list[ContentSummary]


class SeoRequest(BaseModel):
    kind: Kind
    title: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
    body: Annotated[str, StringConstraints(min_length=1, max_length=200_000)]
    category: ShortText = ""


class SeoSuggestion(BaseModel):
    seo: SeoPack
    social: SocialCopy
    excerpt: str
    tags: list[str]
    slug: str
    image_alt_hint: str


class CoverRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    kind: Kind
    title: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=200)]
    body: Annotated[str, StringConstraints(max_length=200_000)] = ""
    category: ShortText = ""
    # The author's idea, in any words. The AI turns it into a concrete scene; empty means it proposes one from the piece.
    concept: Annotated[str, StringConstraints(strip_whitespace=True, max_length=300)] = ""
    # True when `concept` is already a visual scene (e.g. one returned earlier) and should be rendered as-is.
    literal: bool = False


class CoverCandidate(BaseModel):
    url: HttpUrl
    width: int
    height: int


class CoverResult(BaseModel):
    concept: str
    style_version: str
    model: str
    alt: str
    candidates: list[CoverCandidate]
    # How many of the requested renders failed (shown so a partial result isn't mistaken for the whole set).
    failed: int = 0


class SubscribeIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    email: EmailStr
    source: ShortText = ""


class Topic(StrEnum):
    speaking = "Speaking"
    advisory = "Advisory"
    media = "Media"
    other = "Something else"


class ContactIn(BaseModel):
    model_config = ConfigDict(extra="forbid")
    name: Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=120)]
    email: EmailStr
    topic: Topic
    message: Annotated[str, StringConstraints(strip_whitespace=True, min_length=10, max_length=5000)]


class Subscriber(BaseModel):
    id: str
    email: EmailStr
    source: str = ""
    created_at: datetime = Field(default_factory=utcnow)


class ContactMessage(ContactIn):
    model_config = ConfigDict(extra="ignore")
    id: str
    created_at: datetime = Field(default_factory=utcnow)


class MediaOut(BaseModel):
    url: HttpUrl
    content_type: str
    bytes: int


class Problem(BaseModel):
    """RFC 9457-style error body; `detail` is safe to show to the user."""

    title: str
    detail: str
    status: int
